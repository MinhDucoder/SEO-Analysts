// ── Reports (1 per completed audit = 31) ─────────────────────────────────
// Convention: REPORT_ID === '99999999-8888-...' with the same 12-char tail
// as the source audit. Generator helper below builds it deterministically.
export function deriveReportId(auditId: string): string {
  const tail = auditId.slice(-12);
  return `99999999-8888-8888-8888-${tail}`;
}

export function deriveReportCwvId(reportId: string): string {
  const tail = reportId.slice(-12);
  return `99999999-8a88-8a88-8a88-${tail}`;
}

